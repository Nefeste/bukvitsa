/** Слово: кириллица и ё; дефис внутри слова — тоже часть слова («кое-как»). */
export const WORD = /[А-Яа-яЁё]+(?:-[А-Яа-яЁё]+)*/g;

/** Частые буквы — из них берутся лишние плитки, чтобы ряд не подсказывал ответ редкими буквами. */
export const COMMON = 'ОЕАИНТСРВЛКМДПУ';

/** Для сравнения: прописные, ё как е. */
export function norm(s: string): string {
  return s.toUpperCase().replace(/Ё/g, 'Е');
}

