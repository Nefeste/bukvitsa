// Типы движка «Буквицы»: задача, ответ игрока, итог. Движок чистый (устав, «Код»): без React,
// без Date и Math.random; дата приходит аргументом строкой «ГГГГ-ММ-ДД».

/**
 * Вид задачи (docs/08-game-design.md, «Виды задач»):
 * - `gap` — пословица с пропущенным словом, слово собирается из ряда букв;
 * - `ending` — начало пословицы, конец выбирается из четырёх;
 * - `parts` — пословица рассыпана на части, их нужно сложить по порядку;
 * - `extra` — в одном слове лишняя буква, нужно найти это слово.
 */
export type Kind = 'gap' | 'ending' | 'parts' | 'extra';

/** Сложность: 1 — лёгкая, 3 — трудная. Ставит сборка содержания по правилам 08-game-design.md. */
export type Level = 1 | 2 | 3;

/** Задача в сборке: всё, что нужно движку и экрану, уже разрешено сборкой (tools/content/build.ts). */
export interface Task {
  /** вечный идентификатор (устав, «Код»): `t.<тетрадь>.<n>` или `d.<n>` */
  id: string;
  kind: Kind;
  level: Level;
  /** пословица целиком — как в источнике, дословно */
  text: string;
  /** идентификатор пословицы в источнике: `dal.<раздел>.<n>` */
  proverb: string;
  /** раздел Даля — «Счастье — удача» */
  section: string;
  /** gap, extra: номер слова среди слов пословицы (с нуля) */
  word?: number;
  /** ending: с какого слова начинается конец */
  cut?: number;
  /** ending: три чужих конца — из других пословиц того же источника */
  wrong?: string[];
  /** parts: с каких слов начинаются части (первая — 0) */
  starts?: number[];
  /** extra: куда в слове вставлена буква и какая */
  at?: number;
  letter?: string;
}

/** Слово или промежуток между словами. */
export interface Token {
  text: string;
  /** слово (буквы и дефис внутри) или нет (пробелы, знаки) */
  word: boolean;
  /** номер слова среди слов, у промежутка — -1 */
  n: number;
}

/** Как игрок решил задачу — для итога дня и «Поделиться». */
export type Mark = 'clean' | 'helped' | 'shown';

export interface Result {
  /** решена (верно или с открытым ответом) */
  done: boolean;
  /** сколько подсказок взял */
  hints: number;
  /** сколько раз ошибся */
  mistakes: number;
  /** открыл ответ, не решив */
  shown: boolean;
}

export const EMPTY_RESULT: Result = { done: false, hints: 0, mistakes: 0, shown: false };
